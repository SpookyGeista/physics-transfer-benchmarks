"""Freeze all Main2 design dependencies before any reserved history is drawn.

Local source/model snapshot, not an external registration. No simulator starts
and no preparation profile is generated by this command.
"""
from pathlib import Path
import datetime
import hashlib
import json
import shutil
import sys

ROOT=Path(__file__).resolve().parents[1]
REPO=ROOT.parent
sys.path.insert(0,str(ROOT/'costed_benchmark'))
import generate_main2 as generation
import evaluate_main2 as evaluation


def sha(path):return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def main():
    target=ROOT/'locks/main2'
    if target.exists():raise FileExistsError('Existing Main2 lock retained')
    for folder in ('native_main2','observer_main2','statistics_main2'):
        if (ROOT/'results'/folder).exists():raise ValueError(f'Main2 output already exists: {folder}')
    cfg_path=ROOT/'costed_benchmark/main2_native.json'
    cfg=json.loads(cfg_path.read_text())
    generation.validate_config(cfg)
    review=ROOT/'reports/main2_pretest_review.md'
    reviewed=[ROOT/'costed_benchmark'/name for name in ('generate_main2.py','evaluate_main2.py',
        'main2_native.json','main2_evaluation.json','main2_protocol.md')]
    reviewed.extend([Path(__file__).resolve(),ROOT/'tests/test_main2_generation.py',
        ROOT/'costed_benchmark/test_main2_evaluation.py'])
    if not all(sha(path) in review.read_text() for path in reviewed):
        raise ValueError('Independent review does not cover current final sources')
    files=set(generation.authorization_source_paths(cfg_path))|set(reviewed)
    files.update([review,ROOT/'reports/main2_pretest_review.json',ROOT/'reports/pi_numerical_refinement.md',
        ROOT/'reports/pi_inference_review.md',ROOT/'reports/bounded_mle_review.md',
        ROOT/'costed_benchmark/convergence/protocol.md',ROOT/'costed_benchmark/convergence/run_mle.py',
        ROOT/'results/costed_pi_pooled_error_addendum_v1/summary.json'])
    hashes={str(p.resolve()):sha(p) for p in sorted(files)}
    lock=dict(schema_version=1,role='paper_study_main2_test_authorization',status='locked',split='test',
        preparation_seeds=cfg['preparation_seeds'],config_sha256=sha(cfg_path),sources_sha256=hashes,
        created_utc=datetime.datetime.now(datetime.timezone.utc).isoformat(),
        scope='Local prospective descriptive Main2 extension; no external registration',
        expected_native_episodes=3456,expected_forecast_rows=51840,
        conclusions_limited_to_discrete_simulation=True,particle_resolution_demonstrated=False,
        native_output=str(ROOT/'results/native_main2'),evaluation_output=str(ROOT/'results/observer_main2'),
        analysis_output=str(ROOT/'results/statistics_main2'))
    target.mkdir(parents=True)
    for filename,digest in hashes.items():
        source=Path(filename);dest=target/'snapshot'/source.relative_to(REPO)
        dest.parent.mkdir(parents=True,exist_ok=True);shutil.copyfile(source,dest)
        if sha(dest)!=digest:raise ValueError('Snapshot mismatch')
    path=target/'test_authorization.json'
    with path.open('x') as stream:stream.write(json.dumps(lock,indent=2)+'\n')
    generation.verify_main2_lock(cfg,cfg_path,path,{str(p):sha(p) for p in generation.source_paths(cfg_path)})
    evaluation.verify_authorization(path)
    print(json.dumps(dict(lock=str(path),sha256=sha(path),files=len(hashes)),indent=2))


if __name__=='__main__':main()
